"""Stage 0: turn each question into visual cues once, and store them.

Cues are generated by the edge model from the question text alone (decision D18) and written to
    <cache_dir>/cues/<model_tag>__<key>/cues.jsonl     one line per question: {"id", "query", "cues", "raw"}
so the embedding stage and every later experiment reuse exactly the same cues. Any other source of cues
(GPT, hand-written) just needs to produce the same file.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from .cues import CUE_PROMPT, parse_cue_json
from .eval.datasets import Sample


def cue_meta(cfg: dict) -> dict:
    return {"model_id": cfg["edge"]["model_id"], "dtype": cfg["edge"].get("dtype"), "n_cues": cfg["cues"]["n_cues"],
            "prompt_hash": hashlib.sha1(CUE_PROMPT.encode()).hexdigest()[:10], "source": "edge_text_only"}


def cue_dir(cfg: dict, meta: dict) -> Path:
    key = hashlib.sha1(json.dumps(meta, sort_keys=True).encode()).hexdigest()[:8]
    return Path(cfg["matcher"]["cache_dir"]) / "cues" / f"{meta['model_id'].split('/')[-1]}__{key}"


def load_cues(path: str | Path) -> dict[str, list[str]]:
    out = {}
    with open(path) as f:
        for line in f:
            if line.strip():
                r = json.loads(line)
                out[r["id"]] = r["cues"]
    return out


def run_cues(samples: list[Sample], edge, cfg: dict, out_file: Path, log=print) -> dict[str, list[str]]:
    """Parse cues for every question that does not have them yet (resumable). Returns id -> cues."""
    have = load_cues(out_file) if out_file.exists() else {}
    with open(out_file, "a") as f:
        for s in samples:
            if s.id in have:
                continue
            raw = edge.complete(CUE_PROMPT.format(query=s.query, n=cfg["cues"]["n_cues"]), images=None, max_new_tokens=160)
            cues = parse_cue_json(raw)[: cfg["cues"]["n_cues"]] or [s.query]
            have[s.id] = cues
            f.write(json.dumps({"id": s.id, "query": s.query, "cues": cues, "raw": raw}) + "\n")
            f.flush()
            log(f"  {s.id} {s.task}: {cues}")
    return have
